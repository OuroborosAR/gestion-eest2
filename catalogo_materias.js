function detectarAnioDesdeNombreCurso(nombreCurso) {
  const m = String(nombreCurso || "").trim().match(/^([1-7])/);
  return m ? parseInt(m[1], 10) : 0;
}

function obtenerMapaEspecialidadesCursos() {
  try {
    return JSON.parse(localStorage.getItem("eest2_especialidades_cursos") || "{}");
  } catch (e) {
    return {};
  }
}

function guardarEspecialidadCursoLocal(nombreCurso, espKey) {
  if (!nombreCurso || !espKey) return;
  const mapa = obtenerMapaEspecialidadesCursos();
  mapa[nombreCurso] = espKey;
  localStorage.setItem("eest2_especialidades_cursos", JSON.stringify(mapa));
}

function detectarEspecialidadCurso(nombreCurso, materiasActuales) {
  const anio = detectarAnioDesdeNombreCurso(nombreCurso);
  if (anio >= 1 && anio <= 3) return "CICLO_BASICO";

  const mapa = obtenerMapaEspecialidadesCursos();
  if (nombreCurso && mapa[nombreCurso] && CATALOGO_CURRICULAR_EEST2[mapa[nombreCurso]]) {
    return mapa[nombreCurso];
  }

  const textoMat = (materiasActuales || []).map(m => String(m.nombre || m).toLowerCase()).join(" | ");
  if (textoMat.indexOf("naval") !== -1 || textoMat.indexOf("buque") !== -1) return "NAVAL";
  if (textoMat.indexOf("bromatolog") !== -1 || textoMat.indexOf("alimento") !== -1 || textoMat.indexOf("química orgánica") !== -1 || textoMat.indexOf("biología celular") !== -1) {
    return "ALIMENTOS";
  }
  return "ELECTROMECANICA";
}

function obtenerMateriasCatalogo(especialidad, anio) {
  const espObj = CATALOGO_CURRICULAR_EEST2[especialidad];
  if (!espObj) return [];
  const aNum = parseInt(anio, 10);
  if (aNum && espObj.anios[aNum]) return espObj.anios[aNum];

  // Si no se detectó año, devolver todas las materias únicas de la especialidad
  const vistos = new Set();
  const todas = [];
  Object.values(espObj.anios).forEach(lista => {
    lista.forEach(item => {
      const k = item.nombre.toLowerCase();
      if (!vistos.has(k)) {
        vistos.add(k);
        todas.push(item);
      }
    });
  });
  return todas;
}

function parsearHorarioTextoATime(horarioStr) {
  const matches = String(horarioStr || "").match(/(\d{1,2})[:.](\d{2})/g);
  if (matches && matches.length >= 2) {
    const norm = (s) => {
      const p = s.replace(".", ":").split(":");
      return `${p[0].padStart(2, "0")}:${p[1].padStart(2, "0")}`;
    };
    return { inicio: norm(matches[0]), fin: norm(matches[1]) };
  }
  if (matches && matches.length === 1) {
    const p = matches[0].replace(".", ":").split(":");
    return { inicio: `${p[0].padStart(2, "0")}:${p[1].padStart(2, "0")}`, fin: "" };
  }
  return { inicio: "07:40", fin: "09:40" };
}

function formatearHorarioDesdeTime(inicio, fin) {
  const i = String(inicio || "").trim();
  const f = String(fin || "").trim();
  if (i && f) return `${i} A ${f}`;
  return i || f || "";
}

function buscarModalidadEnCatalogo(nombreMateria, especialidad, anio) {
  const norm = (s) => String(s || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toUpperCase();
  const buscado = norm(nombreMateria);
  if (!buscado) return "";

  const lista = obtenerMateriasCatalogo(especialidad, anio);
  const exact = lista.find(m => norm(m.nombre) === buscado);
  if (exact) return exact.modalidad;

  for (const espKey of Object.keys(CATALOGO_CURRICULAR_EEST2)) {
    const anios = CATALOGO_CURRICULAR_EEST2[espKey].anios;
    for (const a of Object.keys(anios)) {
      const hit = anios[a].find(m => norm(m.nombre) === buscado);
      if (hit) return hit.modalidad;
    }
  }
  return "";
}
