const HORAS_24HS_LISTA = (() => {
  const arr = [];
  for (let h = 7; h <= 23; h++) {
    for (let m = 0; m < 60; m += 5) {
      if (h === 23 && m > 0) break;
      arr.push(`${String(h).padStart(2, "0")}:${String(m).padStart(2, "0")}`);
    }
  }
  return arr;
})();

function obtenerClaveTurnoHorario(turnoStr) {
  const up = String(turnoStr || "").toUpperCase();
  if (up.indexOf("TV") !== -1 || up.indexOf("FÍSICA") !== -1 || up.indexOf("FISICA") !== -1) {
    return "MANUAL";
  }
  const esTal = up.indexOf("TALLER") !== -1;
  if (up.indexOf("TT") !== -1) return esTal ? "TT_TALLER" : "TT_TEORIA";
  if (up.indexOf("TM") !== -1) return esTal ? "TM_TALLER" : "TM_TEORIA";
  return "MANUAL";
}

function obtenerPresetsParaTurno(turnoStr) {
  const clave = obtenerClaveTurnoHorario(turnoStr);
  return HORARIOS_PREDEFINIDOS_EEST2[clave] || [];
}

function normalizarHorario24hs(horarioStr) {
  const t = parsearHorarioTextoATime(horarioStr);
  return formatearHorarioDesdeTime(t.inicio, t.fin);
}

function esHorarioPredefinido(horarioStr, turnoStr) {
  const norm = normalizarHorario24hs(horarioStr);
  const lista = turnoStr ? obtenerPresetsParaTurno(turnoStr) : [
    ...HORARIOS_PREDEFINIDOS_EEST2.TM_TEORIA,
    ...HORARIOS_PREDEFINIDOS_EEST2.TM_TALLER,
    ...HORARIOS_PREDEFINIDOS_EEST2.TT_TEORIA,
    ...HORARIOS_PREDEFINIDOS_EEST2.TT_TALLER
  ];
  return lista.some(p => p.val === norm);
}

function obtenerHorarioDefectoParaTurno(turnoStr) {
  const presets = obtenerPresetsParaTurno(turnoStr);
  if (presets.length > 0) return presets[0].val;
  const up = String(turnoStr || "").toUpperCase();
  if (up.indexOf("TV") !== -1) return "18:20 A 20:20";
  if (up.indexOf("FÍSICA") !== -1 || up.indexOf("FISICA") !== -1) return "08:00 A 09:00";
  return "07:30 A 09:30";
}

